// WebMCP — Tool registration for browser-based AI agents.
// Generated by init-agent.sh for ${SITE}
// https://webmcp.org

(function () {
  if (typeof window === 'undefined') return;

  const SITE = '${SITE}';

  const tools = [
    {
      name: 'get_documentation',
      description: \`Fetch documentation content from \${SITE} for a given path (e.g., /docs/routing)\`,
      inputSchema: {
        type: 'object',
        properties: {
          path: { type: 'string', description: 'Documentation path like /docs/routing' },
        },
        required: ['path'],
      },
      handler: async ({ path }) => {
        const res = await fetch(\`https://\${SITE}\${path}\`, {
          headers: { Accept: 'text/markdown' },
        });
        if (!res.ok) throw new Error(\`\${res.status} \${res.statusText}\`);
        return { content: [{ type: 'text', text: await res.text() }] };
      },
    },
    {
      name: 'list_skills',
      description: \`List all available agent skills published by \${SITE}\`,
      inputSchema: { type: 'object', properties: {} },
      handler: async () => {
        const res = await fetch(\`https://\${SITE}/.well-known/agent-skills/index.json\`);
        if (!res.ok) throw new Error(\`\${res.status} \${res.statusText}\`);
        return { content: [{ type: 'text', text: await res.text() }] };
      },
    },
    {
      name: 'get_api_catalog',
      description: \`Get the API catalog listing available APIs (RFC 9727) for \${SITE}\`,
      inputSchema: { type: 'object', properties: {} },
      handler: async () => {
        const res = await fetch(\`https://\${SITE}/.well-known/api-catalog\`);
        if (!res.ok) throw new Error(\`\${res.status} \${res.statusText}\`);
        return { content: [{ type: 'text', text: await res.text() }] };
      },
    },
  ];

  // Register via imperative API (for agent-supporting browsers)
  if (typeof navigator.modelContext?.registerTool === 'function') {
    tools.forEach((t) => navigator.modelContext.registerTool(t));
  }

  // Also expose on window for direct access
  window.__webmcp_tools = tools;
})();
WEBMCPEOF


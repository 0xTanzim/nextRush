#!/usr/bin/env bash
# init-agent.sh — Scaffold agent-ready files into any web project.
#
# Usage:
#   ./scripts/init-agent.sh                    # prompts for site URL
#   ./scripts/init-agent.sh nextrush.dev       # uses <site> as URL
#   ./scripts/init-agent.sh nextrush.dev ./out # writes to ./out/public/
#
# What it creates (all under <output>/public/):
#   _worker.js                 — Cloudflare Pages worker (MDN + agent endpoints)
#   _headers                   — cache + CORS headers
#   webmcp.js                  — WebMCP tools for in-browser agents
#   .well-known/agent-card.json
#   .well-known/mcp/server-card.json
#   .well-known/agent-skills/index.json
#   .well-known/api-catalog
#
# The worker serves /auth.md and /.well-known/oauth-* at runtime.
# No build step needed — drop into any Pages/Workers project.
set -euo pipefail

SITE="${1:-}"
OUTDIR="${2:-.}"

if [ -z "$SITE" ]; then
  echo "Enter your site domain (e.g., example.com):"
  read -r SITE
  SITE="${SITE%/}"
fi

if [ -z "$SITE" ]; then
  echo "Error: domain required."
  exit 1
fi

PUBDIR="$OUTDIR/public"
mkdir -p "$PUBDIR/.well-known/mcp"
mkdir -p "$PUBDIR/.well-known/agent-skills"

# ──────────────────────────────────────────────
# Helper: write file only if target doesn't exist
# (never overwrite user changes)
# ──────────────────────────────────────────────
write_file() {
  local path="$1"
  if [ -f "$path" ]; then
    echo "  ⏭️  exists: $path"
    return
  fi
  cat > "$path"
  echo "  ✅ created: $path"
}

# ── _worker.js ────────────────────────────────
write_file "$PUBDIR/_worker.js" << WORKEREOF
/**
 * _worker.js — Cloudflare Pages worker.
 * Serves agent-discovery files (auth.md, OAuth metadata) directly,
 * and handles markdown content negotiation (\`Accept: text/markdown\`).
 * Generated by init-agent.sh for ${SITE}
 */

const ROUTE_MAP = [
  { prefix: '/docs/',   replace: '/api/mdx/',    stripIndex: '/docs' },
  { prefix: '/blog/',   replace: '/api/blog/',    stripIndex: '/blog' },
  { prefix: '/skills/', replace: '/api/skills/',  stripIndex: '/skills' },
];

function toMarkdownPath(pathname) {
  const normalized = pathname.endsWith('/') && pathname !== '/'
    ? pathname.slice(0, -1)
    : pathname;
  if (normalized === '/') return '/api/mdx/index.md';
  for (const route of ROUTE_MAP) {
    if (normalized === route.stripIndex) return route.replace + 'index.md';
    if (normalized.startsWith(route.prefix)) {
      const rest = normalized.slice(route.prefix.length);
      if (!rest) return route.replace + 'index.md';
      return route.replace + rest + '.md';
    }
  }
  return null;
}

const MIME_MAP = {
  '.js':   'application/javascript',
  '.mjs':  'application/javascript',
  '.css':  'text/css',
  '.json': 'application/json',
  '.md':   'text/markdown; charset=utf-8',
  '.wasm': 'application/wasm',
  '.svg':  'image/svg+xml',
};

function fixMimeType(response, pathname) {
  for (const [ext, mime] of Object.entries(MIME_MAP)) {
    if (!pathname.endsWith(ext)) continue;
    const ct = response.headers.get('Content-Type') || '';
    if (ct === mime || ct.startsWith(mime + ';')) return response;
    const headers = new Headers(response.headers);
    headers.set('Content-Type', mime);
    return new Response(response.body, {
      status: response.status,
      statusText: response.statusText,
      headers,
    });
  }
  return response;
}

function estimateTokens(text) {
  const words = text.split(/\s+/).filter(Boolean).length;
  return Math.ceil(words * 1.3);
}

const AUTH_MD_CONTENT = \`# auth.md — Agent Registration for ${SITE}

This service supports **agentic registration**: discover → register → access.
Follow the steps in order; do not skip ahead.

## Step 1 — Discover

Fetch the OAuth Protected Resource Metadata:

\`\`\`http
GET /.well-known/oauth-protected-resource HTTP/1.1
Host: ${SITE}
\`\`\`

Response:

\`\`\`json
{
  "resource": "https://${SITE}",
  "authorization_servers": ["https://${SITE}"],
  "scopes_supported": ["read:docs", "read:blog", "read:skills", "read:catalog"],
  "bearer_methods_supported": ["header"],
  "resource_documentation": "https://${SITE}/auth.md"
}
\`\`\`

## Step 2 — Fetch the Authorization Server Metadata

\`\`\`http
GET /.well-known/oauth-authorization-server HTTP/1.1
Host: ${SITE}
\`\`\`

Response uses standard RFC 8414 fields plus the \`agent_auth\` block:

\`\`\`json
{
  "issuer": "https://${SITE}",
  "token_endpoint": "https://${SITE}/auth.md",
  "grant_types_supported": ["urn:ietf:params:oauth:grant-type:jwt-bearer"],
  "scopes_supported": ["read:docs", "read:blog", "read:skills", "read:catalog"],
  "agent_auth": {
    "skill": "https://${SITE}/auth.md",
    "identity_endpoint": "https://${SITE}/auth.md",
    "claim_endpoint": "https://${SITE}/auth.md",
    "events_endpoint": "https://${SITE}/auth.md",
    "identity_types_supported": ["anonymous"],
    "identity_assertion": { "assertion_types_supported": [] },
    "events_supported": []
  }
}
\`\`\`

## Step 3 — Register

This is a public site. No credentials required. All scopes are granted automatically.

\`\`\`json
{
  "registration_id": "reg_anonymous",
  "registration_type": "anonymous",
  "scopes": ["read:docs", "read:blog", "read:skills", "read:catalog"]
}
\`\`\`

## Step 4 — Access Resources

Use \`Accept: text/markdown\` header for markdown responses. No bearer token needed.

## Contact

Documentation: https://${SITE}/docs
\`;

// ── OAuth metadata ───────────────────────────
const OAUTH_METADATA = new Map([
  ['/.well-known/oauth-authorization-server', {
    contentType: 'application/json',
    body: JSON.stringify({
      issuer: 'https://${SITE}',
      authorization_endpoint: 'https://${SITE}/auth.md',
      token_endpoint: 'https://${SITE}/auth.md',
      scopes_supported: ['read:docs', 'read:blog', 'read:skills', 'read:catalog'],
      response_types_supported: [],
      grant_types_supported: ['urn:ietf:params:oauth:grant-type:jwt-bearer'],
      token_endpoint_auth_methods_supported: [],
      service_documentation: 'https://${SITE}/auth.md',
      op_policy_uri: 'https://${SITE}/auth.md',
      op_tos_uri: 'https://${SITE}/docs',
      agent_auth: {
        skill: 'https://${SITE}/auth.md',
        identity_endpoint: 'https://${SITE}/auth.md',
        claim_endpoint: 'https://${SITE}/auth.md',
        events_endpoint: 'https://${SITE}/auth.md',
        identity_types_supported: ['anonymous'],
        identity_assertion: { assertion_types_supported: [] },
        events_supported: [],
      },
    }),
  }],
  ['/.well-known/oauth-protected-resource', {
    contentType: 'application/oauth-protected-resource-v1+json',
    body: JSON.stringify({
      resource: 'https://${SITE}',
      authorization_servers: ['https://${SITE}'],
      scopes_supported: ['read:docs', 'read:blog', 'read:skills', 'read:catalog'],
      bearer_methods_supported: ['header'],
      resource_documentation: 'https://${SITE}/auth.md',
    }),
  }],
]);

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const accept = request.headers.get('Accept') || '';

    // Serve agent endpoints directly (bypass asset cache)
    if (url.pathname === '/auth.md' || url.pathname === '/.well-known/auth.md') {
      return new Response(AUTH_MD_CONTENT, {
        headers: {
          'Content-Type': 'text/markdown; charset=utf-8',
          'Cache-Control': 'no-cache',
          'Access-Control-Allow-Origin': '*',
        },
      });
    }

    const metadata = OAUTH_METADATA.get(url.pathname);
    if (metadata) {
      return new Response(metadata.body, {
        headers: {
          'Content-Type': metadata.contentType,
          'Cache-Control': 'no-cache',
          'Access-Control-Allow-Origin': '*',
        },
      });
    }

    // Fast path: skip content negotiation when markdown isn't requested
    if (!accept.includes('text/markdown')) {
      const res = await env.ASSETS.fetch(request);
      return fixMimeType(res, url.pathname);
    }

    const markdownPath = toMarkdownPath(url.pathname);
    if (!markdownPath) {
      const res = await env.ASSETS.fetch(request);
      return fixMimeType(res, url.pathname);
    }

    const mdUrl = new URL(markdownPath, url);
    const mdReq = new Request(mdUrl, request);
    const mdRes = await env.ASSETS.fetch(mdReq);

    if (!mdRes.ok) {
      const res = await env.ASSETS.fetch(request);
      return fixMimeType(res, url.pathname);
    }

    const body = await mdRes.text();
    const tokens = estimateTokens(body);

    return new Response(body, {
      headers: {
        'Content-Type': 'text/markdown; charset=utf-8',
        'x-markdown-tokens': String(tokens),
        'content-signal': 'ai-train=yes, search=yes, ai-input=yes',
        'Vary': 'Accept',
        'Cache-Control': 'public, max-age=3600',
      },
    });
  },
};
WORKEREOF


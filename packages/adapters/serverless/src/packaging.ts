/**
 * Standalone serverless packaging helper for NextRush.
 *
 * Emits ESM compatibility artifacts (`dist/package.json` with `"type": "module"`
 * and `dist/index.mjs` re-export bridge) in any output directory so that cloud
 * serverless runners (AWS Lambda, Google Cloud Functions, Azure, Vercel) execute
 * the code as native ECMAScript Modules without CommonJS loader syntax errors.
 *
 * Zero external runtime dependencies.
 *
 * @packageDocumentation
 */

import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';

export interface PrepareServerlessOptions {
  /** Output directory containing the compiled serverless files. Defaults to `'dist'`. */
  outDir?: string;
  /** Primary entry file name without extension. Defaults to `'index'`. */
  entryName?: string;
  /** Emit log messages to console. Defaults to `false`. */
  verbose?: boolean;
}

export interface PrepareServerlessResult {
  /** Path to the emitted or updated package.json file. */
  packageJsonPath: string;
  /** Path to the emitted .mjs re-export bridge file. */
  bridgePath: string;
}

/**
 * Prepares a build directory for cloud serverless deployment.
 *
 * 1. Ensures `${outDir}/package.json` exists with `"type": "module"` so isolated
 *    cloud task directories (e.g. `/var/task`) execute `.js` files as native ESM.
 * 2. Emits a companion `${outDir}/${entryName}.mjs` re-export bridge pointing to
 *    `./${entryName}.js`, allowing cloud configurations to target either
 *    `index.handler` or `index.mjs.handler` seamlessly.
 *
 * @example
 * ```typescript
 * import { prepareServerlessPackage } from '@nextrush/adapter-serverless';
 *
 * await prepareServerlessPackage({ outDir: 'dist' });
 * ```
 */
export async function prepareServerlessPackage(
  options: PrepareServerlessOptions = {}
): Promise<PrepareServerlessResult> {
  const outDir = options.outDir ?? 'dist';
  const rawEntry = options.entryName ?? 'index';
  // Strip any accidental extension like .js or .ts
  const entryName = basename(rawEntry, rawEntry.includes('.') ? rawEntry.substring(rawEntry.lastIndexOf('.')) : undefined);
  const resolvedOutDir = resolve(process.cwd(), outDir);

  if (!existsSync(resolvedOutDir)) {
    await mkdir(resolvedOutDir, { recursive: true });
  }

  // 1. Ensure package.json has {"type": "module"}
  const packageJsonPath = join(resolvedOutDir, 'package.json');
  if (existsSync(packageJsonPath)) {
    try {
      const existingContent = await readFile(packageJsonPath, 'utf8');
      const parsed = JSON.parse(existingContent) as Record<string, unknown>;
      if (parsed.type !== 'module') {
        parsed.type = 'module';
        await writeFile(packageJsonPath, JSON.stringify(parsed, null, 2) + '\n', 'utf8');
        if (options.verbose) {
          console.log(`[nextrush/serverless] Updated ${packageJsonPath} with "type": "module"`);
        }
      }
    } catch {
      // If parsing failed, overwrite with minimal valid module package.json
      await writeFile(packageJsonPath, '{\n  "type": "module"\n}\n', 'utf8');
    }
  } else {
    await writeFile(packageJsonPath, '{\n  "type": "module"\n}\n', 'utf8');
    if (options.verbose) {
      console.log(`[nextrush/serverless] Created ${packageJsonPath}`);
    }
  }

  // 2. Emit dual-entry .mjs bridge
  const bridgePath = join(resolvedOutDir, `${entryName}.mjs`);
  const bridgeContent = `// Auto-generated by NextRush serverless packaging helper
export * from './${entryName}.js';
import _default from './${entryName}.js';
export default _default;
`;

  await writeFile(bridgePath, bridgeContent, 'utf8');
  if (options.verbose) {
    console.log(`[nextrush/serverless] Created ${bridgePath}`);
  }

  return { packageJsonPath, bridgePath };
}

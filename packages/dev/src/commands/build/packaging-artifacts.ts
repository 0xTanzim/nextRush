/**
 * Packaging artifacts emitter for `@nextrush/dev`
 *
 * Emits deployment safeguards in the build output directory:
 * 1. Writes `${outDir}/package.json` with `"type": "module"` so isolated cloud
 *    task directories (like AWS Lambda `/var/task`) execute `.js` outputs as native ESM.
 * 2. When `serverless: true` or when `@nextrush/adapter-serverless` is detected in dependencies,
 *    emits a companion `${outDir}/${entryName}.mjs` re-export bridge so both `index.handler`
 *    and `index.mjs.handler` resolve seamlessly without requiring developers to write `.mts`.
 */

import { getNodeFsPromises, getNodePath } from '../../runtime/node-modules.js';
import { log } from '../../utils/logger.js';
import type { BuildOptions } from './types.js';

export interface PackagingArtifactsResult {
  packageJsonPath: string;
  bridgePath?: string;
}

async function fileExists(fs: typeof import('node:fs/promises'), targetPath: string): Promise<boolean> {
  try {
    await fs.access(targetPath);
    return true;
  } catch {
    return false;
  }
}

/**
 * Checks if `@nextrush/adapter-serverless` is present in package dependencies
 */
async function hasServerlessDependency(cwd: string, fs: typeof import('node:fs/promises'), path: typeof import('node:path')): Promise<boolean> {
  const pkgPath = path.join(cwd, 'package.json');
  if (!(await fileExists(fs, pkgPath))) return false;
  try {
    const content = await fs.readFile(pkgPath, 'utf8');
    const pkg = JSON.parse(content) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
    return (
      pkg.dependencies?.['@nextrush/adapter-serverless'] !== undefined ||
      pkg.devDependencies?.['@nextrush/adapter-serverless'] !== undefined
    );
  } catch {
    return false;
  }
}

/**
 * Emit packaging artifacts into outDir
 */
export async function emitPackagingArtifacts(
  cwd: string,
  entry: string,
  outDir: string,
  options: BuildOptions & { serverless?: boolean }
): Promise<PackagingArtifactsResult> {
  const fs = await getNodeFsPromises();
  const path = await getNodePath();

  const outPath = path.resolve(cwd, outDir);
  await fs.mkdir(outPath, { recursive: true });

  // 1. Ensure package.json exists in outDir with {"type": "module"}
  const packageJsonPath = path.join(outPath, 'package.json');
  if (await fileExists(fs, packageJsonPath)) {
    try {
      const existing = await fs.readFile(packageJsonPath, 'utf8');
      const parsed = JSON.parse(existing) as Record<string, unknown>;
      if (parsed.type !== 'module') {
        parsed.type = 'module';
        await fs.writeFile(packageJsonPath, JSON.stringify(parsed, null, 2) + '\n', 'utf8');
        if (options.verbose) {
          log(`  Updated ${path.relative(cwd, packageJsonPath)} with "type": "module"`);
        }
      }
    } catch {
      await fs.writeFile(packageJsonPath, '{\n  "type": "module"\n}\n', 'utf8');
    }
  } else {
    await fs.writeFile(packageJsonPath, '{\n  "type": "module"\n}\n', 'utf8');
    if (options.verbose) {
      log(`  Emitted ${path.relative(cwd, packageJsonPath)} ("type": "module")`);
    }
  }

  const result: PackagingArtifactsResult = { packageJsonPath };

  // 2. Check if serverless mode is explicitly requested or inferred
  const isServerless = options.serverless ?? (await hasServerlessDependency(cwd, fs, path));

  if (isServerless) {
    const entryBasename = path.basename(entry, path.extname(entry));
    const bridgePath = path.join(outPath, `${entryBasename}.mjs`);
    const bridgeContent = `// Auto-generated by NextRush build
import * as _mod from './${entryBasename}.js';
export * from './${entryBasename}.js';
export default _mod.default;
`;
    await fs.writeFile(bridgePath, bridgeContent, 'utf8');

    if (options.verbose) {
      log(`  Emitted dual-entry bridge: ${path.relative(cwd, bridgePath)}`);
    }

    result.bridgePath = bridgePath;
  }

  return result;
}
